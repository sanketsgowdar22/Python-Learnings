num_1 = int(input("Enter the number:"))

if(num_1 % 2 == 0) and (num_1 % 3 == 0):
    print(f"The {num_1} is divisible by 2 & 3")
elif(num_1 % 3 == 0):
    print(f"The {num_1} is divisible by 3")
elif(num_1 % 2 == 0):
    print(f"The {num_1} is divisible by 2")
else:
    print(f"The {num_1} is divisible by either")
    
    

        

    
